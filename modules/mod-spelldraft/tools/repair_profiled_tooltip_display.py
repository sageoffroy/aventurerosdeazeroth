#!/usr/bin/env python3
"""Repair visible profiled custom-spell values in the SpellDraft tooltip.

This is a client-only formatter layer. Runtime damage is already owned by the
server profile table; this file makes the post-formatter tooltip consume the
same SpellDraftDamageCurves values instead of trusting static custom DBC
numbers left behind by the historical formatter. Reviewed trigger helpers are
also resolved from reviewed_spell_mutations.json so parent auras such as Molten
Armor display the same level-scaled reactive damage that the server executes.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


PROFILE_TOOLTIP_FILENAME = "AventurerosProfiledTooltip.lua"
DATA_FILENAME = "AventurerosSpellScaling.lua"
TOC_FILENAME = "SpellDraft.toc"
MODULE = Path(__file__).resolve().parent.parent
DEFAULT_MUTATIONS = MODULE / "reviewed_spell_mutations.json"
CUSTOM_ID_OFFSET = 200000


class RepairError(RuntimeError):
    pass


def trigger_damage_map_lua(path: Path = DEFAULT_MUTATIONS) -> str:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise RepairError(f"cannot read reviewed spell mutations {path}: {exc}") from exc

    if data.get("schema_version") != 1 or not isinstance(data.get("mutations"), list):
        raise RepairError(f"{path}: expected schema_version=1 and mutations[]")

    rows: list[str] = []
    for mutation in data["mutations"]:
        helpers = mutation.get("normalize_trigger_spells", [])
        if not helpers:
            continue
        if not isinstance(helpers, list):
            raise RepairError(
                f"{path}: normalize_trigger_spells must be a list for {mutation.get('native_root')}"
            )
        owner = CUSTOM_ID_OFFSET + int(mutation["native_root"])
        runtime_helpers = [CUSTOM_ID_OFFSET + int(helper) for helper in helpers]
        rows.append(
            f"  [{owner}] = {{{', '.join(str(value) for value in runtime_helpers)}}},"
        )
    return "\n".join(rows)


LUA_TEMPLATE = r'''-- Auto-generated by Aventureros de Azeroth.
-- Final visual pass for profile-aware 201xxx spells.
SpellDraft = SpellDraft or {}

local TriggerDamageHelpers = {
__TRIGGER_DAMAGE_MAP__
}

local function TooltipSpellID(tip)
  if not tip or not tip.GetSpell then return nil end
  local _name, second, third = tip:GetSpell()
  local id = tonumber(third) or tonumber(second)
  if not id then return nil end
  if not SpellDraftCustomSpellAliases or not SpellDraftCustomSpellAliases[id] then return nil end
  return id
end

local function SecondsText(ms)
  if not ms then return nil end
  if ms % 1000 == 0 then return tostring(ms / 1000) end
  return string.format("%.1f", ms / 1000)
end

local function RangeText(minimum, maximum)
  minimum = tonumber(minimum)
  maximum = tonumber(maximum)
  if not minimum or not maximum then return nil end
  if maximum < minimum then minimum, maximum = maximum, minimum end
  if minimum == maximum then return tostring(minimum) end
  return tostring(minimum) .. "-" .. tostring(maximum)
end

local function RewriteProfiledTriggerDamage(tip, spellID)
  local helpers = TriggerDamageHelpers[spellID]
  if not helpers then return end

  local level = UnitLevel("player") or 1
  local name = tip:GetName()
  if not name then return end

  for _, helperID in ipairs(helpers) do
    local curve = SpellDraftDamageCurves and SpellDraftDamageCurves[helperID]
    local direct = curve and curve.ranges and curve.ranges[level]
    local replacement = direct and RangeText(direct[1], direct[2])
    if replacement then
      local count = tip:NumLines() or 0
      for i = 2, count do
        local left = _G[name .. "TextLeft" .. i]
        if left then
          local text = left:GetText()
          if text
            and not text:match("^%d+[%.%d]* s%s")
            and not text:lower():match("^%d+[^%d]*mana")
            and not text:lower():match("^%d+[^%d]*maná")
          then
            local updated, changed = text:gsub("(%d+)", replacement, 1)
            if changed > 0 then
              left:SetText(updated)
              break
            end
          end
        end
      end
    end
  end
end

local function RewriteProfiledDamageRanges(tip, spellID)
  local curve = SpellDraftDamageCurves and SpellDraftDamageCurves[spellID]
  if not curve or not curve.ranges then return end

  local level = UnitLevel("player") or 1
  local direct = curve.ranges[level]
  if not direct then return end

  local replacements = {}
  local directText = RangeText(direct[1], direct[2])
  if directText then replacements[#replacements + 1] = directText end

  local dot = curve.dots and curve.dots[level]
  if dot then
    local dotMinimum = tonumber(dot.minimum) or tonumber(dot.total)
    local dotMaximum = tonumber(dot.maximum) or tonumber(dot.total)
    local dotText = RangeText(dotMinimum, dotMaximum)
    if dotText then replacements[#replacements + 1] = dotText end
  end

  if #replacements == 0 then return end

  local name = tip:GetName()
  if not name then return end

  local replacementIndex = 1
  local count = tip:NumLines() or 0
  for i = 2, count do
    if replacementIndex > #replacements then break end
    local left = _G[name .. "TextLeft" .. i]
    if left then
      local text = left:GetText()
      if text then
        local changed = false
        local updated = text:gsub("(%d+)%s*%-%s*(%d+)", function(first, second)
          if replacementIndex > #replacements then
            return first .. "-" .. second
          end
          local replacement = replacements[replacementIndex]
          replacementIndex = replacementIndex + 1
          changed = true
          return replacement
        end)
        if changed then left:SetText(updated) end
      end
    end
  end
end

local function RewriteProfiledCastTime(tip, spellID)
  if not SpellDraft.GetProfiledCastTime then return end
  local castMs = SpellDraft.GetProfiledCastTime(spellID, UnitLevel("player"))
  if not castMs or castMs <= 0 then return end

  local replacement = SecondsText(castMs)
  if not replacement then return end

  local name = tip:GetName()
  if not name then return end
  local count = math.min(tip:NumLines() or 0, 7)
  for i = 2, count do
    local left = _G[name .. "TextLeft" .. i]
    if left then
      local text = left:GetText()
      if text and text:match("^%d+[%.%d]* s%s") then
        local updated, changed = text:gsub("^%d+[%.%d]* s", replacement .. " s", 1)
        if changed > 0 then left:SetText(updated) end
        return
      end
    end
  end
end

local function UpdateProfiledTooltip(tip)
  local spellID = TooltipSpellID(tip)
  if not spellID then return end
  RewriteProfiledTriggerDamage(tip, spellID)
  RewriteProfiledDamageRanges(tip, spellID)
  RewriteProfiledCastTime(tip, spellID)
end

local function HookTooltip(tip)
  if tip and tip.HookScript then tip:HookScript("OnTooltipSetSpell", UpdateProfiledTooltip) end
end

HookTooltip(GameTooltip)
HookTooltip(ItemRefTooltip)
'''

LUA = LUA_TEMPLATE.replace("__TRIGGER_DAMAGE_MAP__", trigger_damage_map_lua())


def repair(client_dir: Path) -> bool:
    addon_dir = client_dir / "Interface" / "AddOns" / "SpellDraft"
    if not addon_dir.is_dir():
        raise RepairError(f"SpellDraft addon directory not found: {addon_dir}")

    data_path = addon_dir / DATA_FILENAME
    if not data_path.is_file():
        raise RepairError(f"profile scaling data not found: {data_path}")

    toc_path = addon_dir / TOC_FILENAME
    if not toc_path.is_file():
        raise RepairError(f"SpellDraft TOC not found: {toc_path}")
    toc = [line.strip() for line in toc_path.read_text(encoding="utf-8").splitlines()]
    if toc.count(PROFILE_TOOLTIP_FILENAME) != 1:
        raise RepairError(
            f"expected exactly one {PROFILE_TOOLTIP_FILENAME} entry in {toc_path}"
        )
    if toc.count(DATA_FILENAME) != 1:
        raise RepairError(f"expected exactly one {DATA_FILENAME} entry in {toc_path}")
    if toc.index(DATA_FILENAME) >= toc.index(PROFILE_TOOLTIP_FILENAME):
        raise RepairError("profile scaling data must load before the profiled tooltip formatter")

    output = addon_dir / PROFILE_TOOLTIP_FILENAME
    changed = not output.is_file() or output.read_text(encoding="utf-8") != LUA
    if changed:
        output.write_text(LUA, encoding="utf-8")
    return changed


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--client-dir", required=True, type=Path)
    args = parser.parse_args()

    try:
        changed = repair(args.client_dir.expanduser().resolve())
    except RepairError as exc:
        raise SystemExit(f"Profiled tooltip display repair aborted: {exc}") from exc

    print("Aventureros profiled tooltip display repaired:")
    print(f"  status: {'patched' if changed else 'already patched'}")
    print("  direct damage: final visible range comes from SpellDraftDamageCurves")
    print("  triggered damage: reviewed parent auras display their normalized helper curve")
    print("  periodic total: final visible value comes from the profiled DoT curve")
    print("  cast time: profiled cast display preserved")
    print("  server/runtime files: untouched")


if __name__ == "__main__":
    main()
